"""PostgreSQL schema used for new shared TALARIA installations."""

POSTGRES_REQUIRED_TABLES = {
    "repositories",
    "scans",
    "findings",
    "finding_occurrences",
    "audit_events",
    "refresh_sessions",
    "organizations",
    "users",
    "organization_memberships",
    "webhook_deliveries",
    "approval_records",
    "github_events",
    "github_repositories",
    "github_check_runs",
    "schema_migrations",
    "request_rate_limits",
    "investigations",
}

POSTGRES_SCHEMA = """
CREATE TABLE IF NOT EXISTS repositories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    path TEXT NOT NULL UNIQUE,
    registered_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text
);
CREATE TABLE IF NOT EXISTS scans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id BIGINT NOT NULL REFERENCES repositories(id),
    started_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text,
    completed_at TEXT,
    finding_count INTEGER NOT NULL DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'running'
        CHECK (status IN ('running', 'completed', 'failed')),
    error_summary TEXT,
    branch TEXT,
    commit_sha TEXT
);
CREATE TABLE IF NOT EXISTS findings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fingerprint TEXT NOT NULL UNIQUE,
    repository_id BIGINT NOT NULL REFERENCES repositories(id),
    payload TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'open' CHECK (status IN (
        'open', 'needs_review', 'confirmed', 'false_positive',
        'accepted_risk', 'fixed', 'reopened'
    )),
    first_seen_at TEXT NOT NULL,
    last_seen_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS finding_occurrences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    finding_id BIGINT NOT NULL REFERENCES findings(id),
    scan_id BIGINT NOT NULL REFERENCES scans(id),
    observed_at TEXT NOT NULL,
    UNIQUE (finding_id, scan_id)
);
CREATE TABLE IF NOT EXISTS audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event TEXT NOT NULL,
    details TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text
);
CREATE TABLE IF NOT EXISTS refresh_sessions (
    id TEXT PRIMARY KEY,
    subject TEXT NOT NULL CHECK (length(subject) > 0),
    token_hash TEXT NOT NULL UNIQUE CHECK (length(token_hash) = 64),
    created_at TEXT NOT NULL,
    expires_at TEXT NOT NULL,
    revoked_at TEXT,
    family_id TEXT,
    replaced_by_id TEXT,
    compromised_at TEXT
);
CREATE TABLE IF NOT EXISTS organizations (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL CHECK (length(name) > 0),
    created_at TEXT NOT NULL,
    is_active SMALLINT NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1))
);
ALTER TABLE repositories ADD COLUMN IF NOT EXISTS organization_id TEXT
    REFERENCES organizations(id) ON DELETE CASCADE;
CREATE TABLE IF NOT EXISTS users (
    id TEXT PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    created_at TEXT NOT NULL,
    is_active SMALLINT NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    is_platform_admin SMALLINT NOT NULL DEFAULT 0
        CHECK (is_platform_admin IN (0, 1)),
    CHECK (length(email) > 3)
);
CREATE TABLE IF NOT EXISTS organization_memberships (
    user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    organization_id TEXT NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
    role TEXT NOT NULL CHECK (role IN (
        'org_admin', 'security_lead', 'security_analyst', 'developer', 'auditor'
    )),
    created_at TEXT NOT NULL,
    PRIMARY KEY (user_id, organization_id)
);
CREATE TABLE IF NOT EXISTS webhook_deliveries (
    delivery_id TEXT PRIMARY KEY,
    event TEXT NOT NULL,
    body_sha256 TEXT NOT NULL,
    received_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS approval_records (
    id TEXT PRIMARY KEY,
    organization_id TEXT NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
    action TEXT NOT NULL CHECK (action IN (
        'github.create_branch', 'github.create_pull_request'
    )),
    resource TEXT NOT NULL,
    requested_by TEXT NOT NULL REFERENCES users(id),
    decided_by TEXT REFERENCES users(id),
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN (
        'pending', 'approved', 'rejected', 'expired'
    )),
    created_at TEXT NOT NULL,
    expires_at TEXT NOT NULL,
    decided_at TEXT,
    consumed_at TEXT,
    CHECK (decided_by IS NULL OR decided_by != requested_by)
);
CREATE TABLE IF NOT EXISTS github_events (
    delivery_id TEXT PRIMARY KEY REFERENCES webhook_deliveries(delivery_id)
        ON DELETE CASCADE,
    event TEXT NOT NULL,
    repository TEXT,
    action TEXT,
    ref TEXT,
    base_ref TEXT,
    commit_sha TEXT,
    pull_request_number INTEGER,
    pull_request_state TEXT,
    merged SMALLINT CHECK (merged IS NULL OR merged IN (0, 1)),
    actor TEXT,
    received_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS schema_migrations (
    version INTEGER PRIMARY KEY,
    checksum TEXT NOT NULL CHECK (length(checksum) = 64),
    applied_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text
);
CREATE INDEX IF NOT EXISTS refresh_sessions_subject_idx
    ON refresh_sessions(subject);
CREATE INDEX IF NOT EXISTS refresh_sessions_expiry_idx
    ON refresh_sessions(expires_at);
CREATE INDEX IF NOT EXISTS refresh_sessions_family_idx
    ON refresh_sessions(family_id);
CREATE INDEX IF NOT EXISTS repositories_organization_idx
    ON repositories(organization_id);
CREATE INDEX IF NOT EXISTS approval_records_org_status_idx
    ON approval_records(organization_id, status, created_at);
CREATE INDEX IF NOT EXISTS approval_records_consumption_idx
    ON approval_records(status, consumed_at, expires_at);
CREATE INDEX IF NOT EXISTS github_events_repository_idx
    ON github_events(repository, received_at);
"""

